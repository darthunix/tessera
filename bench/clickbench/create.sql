    pagecharset           text         OPTIONS (column 'PageCharset'),
    codeversion           integer      OPTIONS (column 'CodeVersion'),
    islink                smallint     OPTIONS (column 'IsLink'),
    isdownload            smallint     OPTIONS (column 'IsDownload'),
    isnotbounce           smallint     OPTIONS (column 'IsNotBounce'),
    funiqid               bigint       OPTIONS (column 'FUniqID'),
    originalurl           text         OPTIONS (column 'OriginalURL'),
