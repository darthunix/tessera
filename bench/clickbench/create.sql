    urlcategoryid         smallint     OPTIONS (column 'URLCategoryID'),
    urlregionid           integer      OPTIONS (column 'URLRegionID'),
    resolutionwidth       smallint     OPTIONS (column 'ResolutionWidth'),
    resolutionheight      smallint     OPTIONS (column 'ResolutionHeight'),
