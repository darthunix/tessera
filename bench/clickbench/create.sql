    watchid               bigint       OPTIONS (column 'WatchID'),
    javaenable            smallint     OPTIONS (column 'JavaEnable'),
    title                 text         OPTIONS (column 'Title'),
    goodevent             smallint     OPTIONS (column 'GoodEvent'),
    eventtime             timestamp    OPTIONS (column 'EventTime', unit 'seconds'),
    eventdate             date         OPTIONS (column 'EventDate', unit 'days'),
    counterid             integer      OPTIONS (column 'CounterID'),
    clientip              integer      OPTIONS (column 'ClientIP'),
    regionid              integer      OPTIONS (column 'RegionID'),
    userid                bigint       OPTIONS (column 'UserID'),
