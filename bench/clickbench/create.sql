-- The table of ClickBench's postgresql/create.sql as a foreign table of
-- the wrapper tessera_parquet over ClickBench's files, read in place. The
-- files name their columns in mixed case, which the option column gives;
-- the times are seconds and days since 1970-01-01, which the option unit
-- gives; HitColor, a char in ClickBench's table, is text, since the
-- wrapper takes no char(n). Before it: CREATE EXTENSION tessera_parquet;
-- CREATE SERVER clickbench FOREIGN DATA WRAPPER tessera_parquet; and in
-- psql, \set files to the files' absolute paths, separated by commas.
