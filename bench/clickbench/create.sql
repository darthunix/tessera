    useragentminor        varchar(255) OPTIONS (column 'UserAgentMinor'),
    cookieenable          smallint     OPTIONS (column 'CookieEnable'),
    javascriptenable      smallint     OPTIONS (column 'JavascriptEnable'),
    ismobile              smallint     OPTIONS (column 'IsMobile'),
    mobilephone           smallint     OPTIONS (column 'MobilePhone'),
    mobilephonemodel      text         OPTIONS (column 'MobilePhoneModel'),
    params                text         OPTIONS (column 'Params'),
    ipnetworkid           integer      OPTIONS (column 'IPNetworkID'),
    traficsourceid        smallint     OPTIONS (column 'TraficSourceID'),
    searchengineid        smallint     OPTIONS (column 'SearchEngineID'),
    searchphrase          text         OPTIONS (column 'SearchPhrase'),
    advengineid           smallint     OPTIONS (column 'AdvEngineID'),
