    os                    smallint     OPTIONS (column 'OS'),
    useragent             smallint     OPTIONS (column 'UserAgent'),
    url                   text         OPTIONS (column 'URL'),
    referer               text         OPTIONS (column 'Referer'),
    isrefresh             smallint     OPTIONS (column 'IsRefresh'),
    referercategoryid     smallint     OPTIONS (column 'RefererCategoryID'),
