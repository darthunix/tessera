#!/usr/bin/env python3
"""Write utils/fmgroids.h for a core before PostgreSQL 14: the F_* names
Tessera uses.

PostgreSQL 14 named the F_* macros by function name and argument types;
an older core, such as Greengage 7 (PostgreSQL 12), names them by the C
function. For every F_* name the sources use that the older core lacks
or gives another function (F_DATE_TIMESTAMP is timestamp(date) there,
date(timestamp) in master), this takes the OID from a master build's
fmgroids.h and defines it only when the older core's catalog has a
function of that OID with the same name, argument types and result. The
others are listed as unavailable: the code that needs them is compiled
out there. The file is made from one core's catalog, Greengage 7's in
the tree; another core of that age makes its own.

Usage: gen_fmgroids.py MASTER_PG_CONFIG GREENGAGE_PG_CONFIG \
    MASTER_SRC GREENGAGE_SRC TESSERA_ROOT > utils/fmgroids.h
"""
import pathlib
import re
import subprocess
import sys


def server_include(pg_config):
    return pathlib.Path(
        subprocess.run([pg_config, "--includedir-server"], check=True,
                       capture_output=True, text=True).stdout.strip())


def macros(path):
    text = path.read_text()
    return {m.group(1): int(m.group(2))
            for m in re.finditer(r"^#define (F_\w+) (\d+)$", text, re.M)}


def catalog(src):
    text = (pathlib.Path(src) / "src/include/catalog/pg_proc.dat").read_text()
    result = {}
    for entry in re.finditer(r"\{[^{}]*\}", text):
        body = entry.group(0)
        fields = dict(re.findall(r"(\w+) => '([^']*)'", body))
        if "oid" in fields:
            result[int(fields["oid"])] = (fields.get("proname"),
                                          fields.get("proargtypes", ""),
                                          fields.get("prorettype"))
    return result


def used_names(root):
    names = set()
    for directory in ("bridge", "runtime", "nodes", "kernels", "include"):
        for path in (pathlib.Path(root) / directory).rglob("*.[ch]"):
            names.update(re.findall(r"\bF_[A-Z0-9_]+\b", path.read_text()))
    return names


def main():
    master_pg, gg_pg, master_src, gg_src, root = sys.argv[1:6]
    master = macros(server_include(master_pg) / "utils/fmgroids.h")
    greengage = macros(server_include(gg_pg) / "utils/fmgroids.h")
    master_procs = catalog(master_src)
    gg_procs = catalog(gg_src)
    defined, unavailable = [], []
    for name in sorted(used_names(root)):
        if name not in master:
            continue
        oid = master[name]
        if greengage.get(name) == oid:
            continue
        # A name Greengage gives another function is redefined too.
        if gg_procs.get(oid) == master_procs.get(oid) and oid in gg_procs:
            defined.append((name, oid, gg_procs[oid], name in greengage))
        else:
            unavailable.append((name, oid, master_procs.get(oid)))
    print("/* Generated by gen_fmgroids.py; do not edit. */")
    print('#include_next "utils/fmgroids.h"')
    print()
    for name, oid, (proname, args, result), clash in defined:
        if clash:
            print(f"#undef {name}\t/* Greengage's names {greengage[name]} */")
        print(f"#define {name} {oid}\t/* {proname}({args}) -> {result} */")
    print()
    print("/* Not in Greengage 7's catalog, compiled out there: */")
    for name, oid, proc in unavailable:
        print(f"/* {name} {oid} {proc} */")


main()
